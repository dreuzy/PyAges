"""Generate readable source or installable-plugin LPM starter projects.

This module handles naming, rendering, and atomic filesystem publication. The
long scientific source templates live separately in :mod:`._lpm_sources` so
the generation workflow remains easy to follow.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
from datetime import date
from pathlib import Path
from textwrap import dedent

import click

from pyages.cli._atomic import atomic_write_text
from pyages.cli.templates._lpm_sources import TEMPLATE_VARIANTS

_VALID_NAME = re.compile(r"^[a-z][a-z0-9_]*$")


def _python_header(summary: str, details: str) -> str:
    """Render the editable provenance header shared by generated Python files.

    ``summary`` becomes the first module-docstring line and ``details`` records
    the file's role and limitations. The current year is inserted while the
    copyright holder deliberately remains a visible author placeholder.
    """
    return dedent(
        f'''\
        # Copyright (c) {date.today().year} [Copyright holder]
        # SPDX-License-Identifier: CECILL-2.1
        # Generated by the PyAges LPM template generator; replace placeholders.

        """{summary}

        {details}
        """

        '''
    )


def _class_name(name: str) -> str:
    """Convert a validated ``snake_case`` model name to a PascalCase prefix.

    For example, ``bounded_power`` becomes ``BoundedPower`` and the caller adds
    the conventional ``Lpm`` suffix. Validation happens before rendering.
    """
    return name.replace("_", " ").title().replace(" ", "")


def _validate_name(name: str) -> None:
    """Require one portable name for files, YAML directories, and entry points.

    Raises
    ------
    ValueError
        If the name does not start with a lowercase letter or contains anything
        other than lowercase letters, digits, and underscores.
    """
    if _VALID_NAME.fullmatch(name) is None:
        raise ValueError(
            "LPM name must be snake_case (lowercase letters, digits, underscores)"
        )


def _registration_fragments(name: str, *, plugin: bool) -> tuple[str, str, str]:
    """Return the imports and registration syntax appropriate to one layout.

    Built-in source files receive ``register_lpm`` and its decorator. External
    packages instead receive ``Path`` and ``LpmDefinition`` imports because
    their entry point advertises a data record and must not mutate the built-in
    registry at import time.
    """
    if plugin:
        return (
            "from pathlib import Path\n",
            "from pyages.lpm.extensions import LpmDefinition",
            "",
        )
    return (
        "",
        "from pyages.lpm.core.registry import register_lpm",
        f'@register_lpm("{name}")\n',
    )


def _model_source(name: str, base: str, *, plugin: bool) -> str:
    """Render an executable scientific starter for one name and model base.

    The selected variant contributes formulas and parameterization. This
    function adds layout-specific registration, an explanatory module header,
    and, for a plugin, the module-level :class:`LpmDefinition` advertised by
    package metadata. Generated mathematics is demonstrative and explicitly
    marked for scientific replacement or review.
    """
    variant = TEMPLATE_VARIANTS[base]
    path_import, registration_import, decorator = _registration_fragments(
        name, plugin=plugin
    )
    source = variant.model_source.format(
        name=name,
        class_name=_class_name(name),
        registration_import=registration_import,
        path_import=path_import,
        decorator=decorator,
    )
    if plugin:
        source += dedent(
            f"""\


            definition = LpmDefinition(
                model_class={_class_name(name)}Lpm,
                parameter_directory=Path(__file__).parent / "data_lpm",
                api_version=1,
            )
            """
        )
    layout_description = (
        "installed external plugin" if plugin else "model shipped inside PyAges"
    )
    header = _python_header(
        f"Complete starter implementation for the {name!r} LPM.",
        (
            f"This module was generated for an {layout_description}. The "
            "implementation is executable so that integration can be checked "
            "immediately, but its formulas and parameter ranges are examples "
            "that require scientific review before production use."
        ),
    )
    return header + source


def _params_source(name: str, base: str) -> str:
    """Render ``params.yaml`` whose names match the selected starter formulas.

    The result includes comments distinguishing mathematical domains from
    operational calibration ranges. Values are syntactically valid examples,
    not scientifically approved defaults for an arbitrary study.
    """
    return TEMPLATE_VARIANTS[base].parameter_source.format(name=name)


def _generate_source_layout(name: str, output: str | None, base: str) -> None:
    """Write an in-tree model and its repository-level parameter document.

    ``output`` changes only the Python model directory. The parameter file is
    always written below the current project's ``data_core/data_lpm`` tree,
    matching the built-in runtime layout. Existing files require separate
    interactive confirmation and are replaced atomically when approved.
    """
    project_root = Path.cwd()
    model_output = (
        project_root / "pyages" / "lpm" / "models"
        if output is None
        else Path(output).resolve()
    )
    model_output.mkdir(parents=True, exist_ok=True)
    model_file = model_output / f"{name}.py"
    params_file = project_root / "data_core" / "data_lpm" / name / "params.yaml"
    params_file.parent.mkdir(parents=True, exist_ok=True)

    overwrite_model = model_file.exists()
    if overwrite_model and not click.confirm(
        f"File {model_file} already exists. Overwrite?"
    ):
        click.echo("Aborted.")
        return
    atomic_write_text(
        model_file,
        _model_source(name, base, plugin=False),
        overwrite=overwrite_model,
    )
    click.echo(click.style("Created:", fg="green") + f" {model_file}")

    overwrite_params = params_file.exists()
    if overwrite_params and not click.confirm(
        f"File {params_file} already exists. Overwrite?"
    ):
        click.echo("Skipping params.yaml")
    else:
        atomic_write_text(
            params_file,
            _params_source(name, base),
            overwrite=overwrite_params,
        )
        click.echo(click.style("Created:", fg="green") + f" {params_file}")
    click.echo(f"Verify with: pyages check lpm {name}")


def _plugin_pyproject(name: str, module_name: str, base: str) -> str:
    """Render standalone build metadata for an installable external provider.

    The result declares base-specific dependencies, one ``pyages.lpms`` entry
    point targeting ``model:definition``, ``src`` package discovery, inclusion
    of ``params.yaml`` in distributions, and the generated test directory.
    """
    distribution_name = f"pyages-lpm-{name.replace('_', '-')}"
    return dedent(
        f'''\
        # Generated by ``pyages new lpm {name} --layout plugin``.
        # Review version constraints and project metadata before publication.

        [build-system]
        requires = ["setuptools>=77", "wheel"]
        build-backend = "setuptools.build_meta"

        [project]
        name = "{distribution_name}"
        version = "0.1.0"
        description = "External {name} LPM for PyAges"
        requires-python = ">=3.12,<3.15"
        dependencies = {TEMPLATE_VARIANTS[base].plugin_dependencies}

        # Installing the distribution records this lightweight advertisement.
        # PyAges imports ``definition`` only when this model is selected.
        [project.entry-points."pyages.lpms"]
        {name} = "{module_name}.model:definition"

        [tool.setuptools.packages.find]
        where = ["src"]

        # Keep params.yaml inside wheels and source distributions.
        [tool.setuptools.package-data]
        {module_name} = ["data_lpm/*/params.yaml"]

        [tool.pytest.ini_options]
        testpaths = ["tests"]
        '''
    )


def _plugin_readme(name: str, module_name: str, base: str) -> str:
    """Render the plugin author's first-use and maintenance instructions.

    The README explains which files require scientific editing, how mathematical
    domains differ from calibration ranges, how to install and check the
    project, and how entry-point discovery works. Base-specific text identifies
    whether SciPy or direct probability methods supply the starter operations.
    """
    base_explanation = TEMPLATE_VARIANTS[base].readme_explanation
    return dedent(
        f"""\
        # External PyAges LPM: `{name}`

        This is a standalone Python package generated by PyAges. Installing it
        makes `{name}` discoverable without modifying the PyAges source tree.
        {base_explanation}

        ## Start here

        1. Edit `src/{module_name}/model.py` and review every formula.
        2. Edit `src/{module_name}/data_lpm/{name}/params.yaml` so its names,
           units, domains, ranges, initial values, and priors match the code.
        3. Replace or extend `tests/test_model.py` with scientific reference cases.
        4. Replace the copyright placeholder and review `pyproject.toml` metadata.

        ## Read parameter limits

        In `params.yaml`, `domain` is the mathematical validity domain, while
        `calibration_range` is the finite interval explored by one calibration
        configuration. `min_inclusive: false` means `value > min`; `true` means
        `value >= min`. `max_inclusive` has the analogous meaning. Keep `init`
        inside the calibration range and the calibration range inside the domain.

        ## Install and verify

        Run these commands from this directory:

        ```console
        python -m pip install -e .
        pyages list lpms
        pyages check lpm {name}
        pytest
        ```

        `pyages check lpm` validates packaging, parameters, probability methods,
        moments, vectorization, and convolution integration. It does not replace
        scientific validation against analytical results or trusted data.

        ## How discovery works

        `pyproject.toml` advertises `{name}` in the `pyages.lpms` entry-point
        group. Installation records that small piece of metadata. PyAges reads
        the metadata while listing models and imports `{module_name}.model`
        only when `{name}` is selected or checked.
        """
    )


def _plugin_init_source(name: str, class_name: str) -> str:
    """Render package exports for the model class and advertised definition.

    Normal users rely on entry-point discovery, but explicit exports keep the
    package unsurprising for tests, type checkers, and advanced direct imports.
    """
    body = dedent(
        f'''\
        from .model import {class_name}Lpm, definition

        __all__ = ["{class_name}Lpm", "definition"]
        '''
    )
    return (
        _python_header(
            f"Public exports for the external {name!r} LPM package.",
            "Most users let PyAges discover ``definition`` from package metadata.",
        )
        + body
    )


def _plugin_test_source(name: str) -> str:
    """Render one installed-boundary smoke test for the generated model.

    The test constructs through :func:`build_lpm`, thereby exercising entry
    point discovery and packaged YAML data, then checks a few probability
    invariants. Its module documentation directs authors to add analytical or
    independently trusted scientific expectations.
    """
    body = dedent(
        f'''\
        import numpy as np

        from pyages.lpm import build_lpm


        def test_{name}_distribution_contract() -> None:
            """Exercise installed discovery and basic probability invariants.

            Construction through ``build_lpm`` proves that the entry point and
            packaged parameter file are visible. The assertions then reject a
            negative PDF, decreasing CDF, or inconsistent median quantile.
            Replace or complement them with exact model-specific expectations.
            """
            model = build_lpm("{name}")
            ages = np.array([0.0, model.mean(), float(model.cdf_inv(0.999))])

            assert model.name == "{name}"
            assert np.all(np.asarray(model.pdf(ages)) >= 0.0)
            assert np.all(np.diff(np.asarray(model.cdf(ages))) >= 0.0)
            assert float(model.cdf(model.cdf_inv(0.5))) >= 0.5
        '''
    )
    return (
        _python_header(
            f"Smoke tests for the generated {name!r} LPM plugin.",
            (
                "Keep this integration test, then add analytical moments, quantiles, "
                "boundary cases, and trusted scientific reference values."
            ),
        )
        + body
    )


def _plugin_files(name: str, base: str) -> dict[Path, str]:
    """Assemble every file in a plugin project without touching the filesystem.

    Returns
    -------
    dict
        Relative paths mapped to UTF-8 text for build metadata, documentation,
        package exports, model code, parameter data, and tests. Separating this
        pure assembly step from publication makes the layout easy to test.
    """
    module_name = f"pyages_lpm_{name}"
    class_name = _class_name(name)
    return {
        Path("pyproject.toml"): _plugin_pyproject(name, module_name, base),
        Path("README.md"): _plugin_readme(name, module_name, base),
        Path("src") / module_name / "__init__.py": _plugin_init_source(
            name, class_name
        ),
        Path("src") / module_name / "model.py": _model_source(name, base, plugin=True),
        Path("src") / module_name / "data_lpm" / name / "params.yaml": _params_source(
            name, base
        ),
        Path("tests") / "test_model.py": _plugin_test_source(name),
    }


def _generate_plugin_layout(name: str, output: str | None, base: str) -> None:
    """Publish a complete plugin directory without exposing partial output.

    All files are first written below a temporary sibling directory. A final
    same-filesystem rename makes the project visible at once; any exception
    removes the staging directory. An existing destination is never merged or
    overwritten.

    Raises
    ------
    FileExistsError
        If the requested destination already exists.
    """
    destination = (
        Path.cwd() / f"pyages-lpm-{name.replace('_', '-')}"
        if output is None
        else Path(output).resolve()
    )
    if destination.exists():
        raise FileExistsError(f"Destination already exists: {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    staged = Path(
        tempfile.mkdtemp(prefix=f".{destination.name}.", dir=destination.parent)
    )
    try:
        for relative_path, content in _plugin_files(name, base).items():
            target = staged / relative_path
            target.parent.mkdir(parents=True, exist_ok=True)
            atomic_write_text(target, content)
        os.rename(staged, destination)
    except BaseException:
        shutil.rmtree(staged, ignore_errors=True)
        raise
    click.echo(click.style("Created plugin project:", fg="green") + f" {destination}")
    click.echo(f"Install: python -m pip install -e {destination}")
    click.echo(f"Verify:  pyages check lpm {name}")


def generate_lpm_template(
    name: str,
    output: str | None,
    base: str,
    layout: str = "source",
) -> None:
    """Generate a complete LPM starter in one of the two supported layouts.

    Parameters
    ----------
    name : str
        Canonical model identifier shared by Python, YAML, configuration, and
        entry-point metadata.
    output : str or None
        Optional model directory for ``source`` layout or complete destination
        project for ``plugin`` layout. Defaults are derived from the current
        working directory.
    base : {"scipy", "root"}
        ``scipy`` delegates standard probability methods to ``LpmScipy``;
        ``root`` generates a complete NumPy implementation from ``LpmBase``.
    layout : {"source", "plugin"}, default="source"
        Generate inside a PyAges checkout or as a separately installable
        entry-point package.

    Raises
    ------
    ValueError
        If ``name``, ``base``, or ``layout`` is unsupported.
    FileExistsError
        If a plugin destination already exists. Source layout uses interactive
        overwrite confirmation instead.

    Notes
    -----
    The generated code is executable so integration can be checked immediately,
    but its formulas, ranges, priors, and tests remain examples requiring
    domain-specific scientific review.
    """
    _validate_name(name)
    if base not in TEMPLATE_VARIANTS:
        raise ValueError(f"Unknown LPM base: {base}")
    if layout == "source":
        _generate_source_layout(name, output, base)
        return
    if layout == "plugin":
        _generate_plugin_layout(name, output, base)
        return
    raise ValueError(f"Unknown LPM layout: {layout}")


